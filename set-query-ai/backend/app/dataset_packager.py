"""
Dataset packager for SatQuery AI.

Asynchronously harvests individual GeoTIFF scenes from Google Earth Engine,
extracts and ensures .tif format, applies ISO-8601 UTC timestamp filenames,
includes an explanatory dataset guide, and packages everything into a single ZIP archive.
"""

from __future__ import annotations

import asyncio
import io
import os
import urllib.request
import zipfile
from datetime import datetime, timezone
from typing import Any, Callable, Coroutine

import ee

from .schemas import ZipProgressMessage

# Storage directory for compiled ZIP archives
DOWNLOADS_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "downloads"))
os.makedirs(DOWNLOADS_DIR, exist_ok=True)

# In-memory registry of completed ZIP files: job_id -> file path
zip_registry: dict[str, dict[str, Any]] = {}


def _download_and_extract_tif(download_url: str) -> bytes:
    """
    Download payload from GEE signed URL.
    If GEE packaged the GeoTIFF inside a ZIP archive, unpack and return the .tif bytes.
    Otherwise return the raw TIFF bytes directly.
    """
    req = urllib.request.Request(
        download_url,
        headers={"User-Agent": "SatQuery-AI/1.0"}
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        content = resp.read()

    # Check for ZIP file magic bytes (PK\x03\x04)
    if content.startswith(b"PK\x03\x04"):
        with zipfile.ZipFile(io.BytesIO(content)) as zf:
            tif_names = [n for n in zf.namelist() if n.lower().endswith((".tif", ".tiff"))]
            if tif_names:
                return zf.read(tif_names[0])
            # If no .tif extension found, return first file in zip
            first_name = zf.namelist()[0]
            return zf.read(first_name)

    return content


def _create_dataset_readme(job_id: str, scene_filenames: list[str], mode: str) -> str:
    """Generate a clear, presentation-ready guide for researchers and judges."""
    now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    
    file_list = "\n".join(f"  - {f}" for f in scene_filenames)
    
    return f"""================================================================================
SatQuery AI — Earth Observation Dataset Archive
================================================================================
Job ID:         {job_id}
Generated:      {now_utc}
Retrieval Mode: {mode.upper()}
Total Files:    {len(scene_filenames)} GeoTIFFs

HOW TO READ THE FILENAMES & TIMESTAMPS:
--------------------------------------------------------------------------------
Every image in this dataset is strictly named using the standardized format:

    SatQuery_[Sensor]_[Modality]_[YYYYMMDD]_[THHMMSSZ].tif

Example:
    SatQuery_S2_Optical_20230615_T103021Z.tif
    -> Sensor:    Sentinel-2 (Copernicus / European Space Agency)
    -> Modality:  Optical Surface Reflectance (RGB: Bands 4, 3, 2)
    -> Date:      June 15, 2023
    -> Time:      10:30:21 UTC (Universal Coordinated Time)

Example:
    SatQuery_S1_SAR_VV_20230616_T174512Z.tif
    -> Sensor:    Sentinel-1 (Copernicus / European Space Agency)
    -> Modality:  Synthetic Aperture Radar (SAR C-Band VV Polarisation)
    -> Date:      June 16, 2023
    -> Time:      17:45:12 UTC

CHRONOLOGICAL TIME-SERIES SORTING:
--------------------------------------------------------------------------------
Because timestamps follow ISO-8601 lexicographical ordering, sorting this
directory alphabetically (A to Z) automatically aligns all acquisitions in
strict chronological order (T1 -> T2 -> ... -> Tn). 

This is ideal for temporal change detection, remote sensing models (EarthDial,
EarthMind, Telescoper), and GIS raster stacks.

GEOSPATIAL & SCIENTIFIC SPECIFICATIONS:
--------------------------------------------------------------------------------
* Format:            GeoTIFF (.tif) with embedded geospatial metadata (CRS / Affine Transform)
* Spatial Resolution: 10 meters per pixel (Sentinel native resolution)
* Optical Source:    COPERNICUS/S2_SR_HARMONIZED (Level-2A Bottom-Of-Atmosphere)
* Radar Source:      COPERNICUS/S1_GRD (Interferometric Wide Swath)

ARCHIVED FILES IN THIS DATASET:
--------------------------------------------------------------------------------
{file_list}

================================================================================
Generated by SatQuery AI — Interactive Satellite Imagery Retrieval System
================================================================================
"""


async def package_dataset_background(
    job_id: str,
    geometry: ee.Geometry,
    optical_res: dict[str, Any] | None,
    sar_res: dict[str, Any] | None,
    mode: str,
    send_progress: Callable[[ZipProgressMessage], Coroutine[Any, Any, None]],
):
    """
    Background worker that fetches full GeoTIFF scenes, packages them into a ZIP,
    and updates progress over the WebSocket.
    """
    job_dir = os.path.join(DOWNLOADS_DIR, job_id)
    os.makedirs(job_dir, exist_ok=True)
    zip_filename = f"SatQuery_Dataset_{job_id[:8]}.zip"
    zip_path = os.path.join(job_dir, zip_filename)

    scenes_to_fetch: list[dict[str, Any]] = []

    # Gather all scene items
    if mode == "timeseries":
        if optical_res and "scenes" in optical_res:
            scenes_to_fetch.extend(optical_res["scenes"])
        if sar_res and "scenes" in sar_res:
            scenes_to_fetch.extend(sar_res["scenes"])

    # Fallback to the primary result URLs if scenes list is empty or in composite mode
    if not scenes_to_fetch:
        if optical_res and optical_res.get("download_url"):
            slug = optical_res.get("filename_slug", "composite")
            scenes_to_fetch.append({
                "type": "direct_url",
                "sensor": "Sentinel-2",
                "filename": f"SatQuery_S2_Optical_{slug}.tif",
                "download_url": optical_res["download_url"],
            })
        if sar_res and sar_res.get("download_url"):
            slug = sar_res.get("filename_slug", "composite")
            scenes_to_fetch.append({
                "type": "direct_url",
                "sensor": "Sentinel-1",
                "filename": f"SatQuery_S1_SAR_VV_{slug}.tif",
                "download_url": sar_res["download_url"],
            })

    total_count = len(scenes_to_fetch)
    if total_count == 0:
        await send_progress(
            ZipProgressMessage(
                job_id=job_id,
                status="failed",
                progress_pct=0,
                message="No satellite scenes available to archive.",
            )
        )
        return

    await send_progress(
        ZipProgressMessage(
            job_id=job_id,
            status="processing",
            progress_pct=5,
            message=f"Beginning background harvest of {total_count} GeoTIFF scenes...",
            total_scenes=total_count,
        )
    )

    loop = asyncio.get_running_loop()
    harvested_files: list[tuple[str, bytes]] = []

    for idx, sc in enumerate(scenes_to_fetch, start=1):
        filename = sc["filename"]
        try:
            download_url = sc.get("download_url")

            # If scene needs on-demand GEE GeoTIFF URL generation:
            if not download_url and sc.get("id"):
                scene_id = sc["id"]
                sensor = sc.get("sensor")

                def _generate_gee_url(s_id=scene_id, s_sensor=sensor, s_filename=filename):
                    raw_img = ee.Image(s_id)
                    if s_sensor == "Sentinel-2":
                        vis_img = (
                            raw_img.select(["B4", "B3", "B2"])
                            .divide(10000)
                            .visualize(min=0.0, max=0.28, gamma=1.3)
                        )
                    else:
                        vis_img = (
                            raw_img.select("VV")
                            .focalMedian(15, "circle", "meters")
                            .unmask(-25)
                            .visualize(min=-22, max=1)
                        )

                    slug_name = os.path.splitext(s_filename)[0]
                    return vis_img.getDownloadURL({
                        "name": slug_name,
                        "region": geometry,
                        "scale": 10,
                        "format": "GEO_TIFF",
                    })

                download_url = await loop.run_in_executor(None, _generate_gee_url)

            # Download GeoTIFF content
            tif_bytes = await loop.run_in_executor(None, _download_and_extract_tif, download_url)
            harvested_files.append((filename, tif_bytes))

            progress_pct = int(10 + (idx / total_count) * 80)
            await send_progress(
                ZipProgressMessage(
                    job_id=job_id,
                    status="processing",
                    progress_pct=progress_pct,
                    message=f"Packaged {idx}/{total_count} GeoTIFFs: {filename}...",
                    total_scenes=total_count,
                )
            )

        except Exception as exc:
            print(f"Warning: Failed to harvest scene {filename}: {exc}")

    if not harvested_files:
        await send_progress(
            ZipProgressMessage(
                job_id=job_id,
                status="failed",
                progress_pct=0,
                message="Failed to harvest GeoTIFF images from Google Earth Engine.",
            )
        )
        return

    # Write ZIP archive
    await send_progress(
        ZipProgressMessage(
            job_id=job_id,
            status="processing",
            progress_pct=95,
            message="Finalizing and compressing dataset ZIP archive...",
            total_scenes=total_count,
        )
    )

    def _write_zip():
        with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            # 1. Add README guide
            readme_text = _create_dataset_readme(
                job_id=job_id,
                scene_filenames=[fn for fn, _ in harvested_files],
                mode=mode,
            )
            zf.writestr("README_DATASET.txt", readme_text)

            # 2. Add each GeoTIFF
            for fn, data in harvested_files:
                zf.writestr(fn, data)

    await loop.run_in_executor(None, _write_zip)

    size_bytes = os.path.getsize(zip_path)
    size_mb = round(size_bytes / (1024 * 1024), 1)

    # Register in registry
    download_rel_url = f"/api/jobs/{job_id}/download-zip"
    zip_registry[job_id] = {
        "file_path": zip_path,
        "filename": zip_filename,
        "size_mb": size_mb,
        "total_scenes": len(harvested_files),
    }

    # Stream final ready status
    await send_progress(
        ZipProgressMessage(
            job_id=job_id,
            status="ready",
            progress_pct=100,
            message=f"Dataset ZIP ready! ({len(harvested_files)} GeoTIFFs · {size_mb} MB)",
            download_url=download_rel_url,
            size_mb=size_mb,
            total_scenes=len(harvested_files),
        )
    )
